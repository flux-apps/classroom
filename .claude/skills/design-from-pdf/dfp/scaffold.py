"""AC8 The deterministic half of the build: tokens, styles.css, provenance, manifest skeleton, preview runtime.

Components, cards, readme and SKILL.md are judgement and belong to the skill procedure; `validate` checks their
structure afterwards. No font binary is ever written: families map to Google Fonts imports (fontmap).
"""
from __future__ import annotations

import json
import os
import re
import shutil
from pathlib import Path

from . import fontmap
from .medium import WEB_MEDIA
from .util import fmt_num, px_rem, slugify

GENERATED = "/* generated by dfp scaffold from _analysis/approved.json - edit analysis.md and re-run, not this file */"
ORDER = ["fonts", "colors", "typography", "spacing", "radii", "borders", "elevation", "page", "motion"]
PRINT_LIKE = {"publication-print", "presentation", "marketing"}

_TYP = re.compile(r"^(?P<family>.+?)\s+(?P<size>\d+(?:\.\d+)?)pt\s+(?P<weight>\d{3})(?P<italic>\s+italic)?"
                  r"(?:\s*/\s*(?P<lh>\d+(?:\.\d+)?)pt)?\s*$")
_LEN = r"\d+(?:\.\d+)?(?:pt|px|mm|cm|in|em|rem|%)"
_LEN_ONLY = re.compile(r"^%s$" % _LEN)
_SIZE2 = re.compile(r"^(%s)[\s,x]+(%s)$" % (_LEN, _LEN))
_MARGIN = re.compile(r"(top|right|bottom|left)\s+(%s)" % _LEN)
_RATIO = re.compile(r"ratio\s+(\d+(?:\.\d+)?)(?:\s+base\s+(%s))?" % _LEN)


class Blocked(Exception):
    pass


def slugify_label(text, prefix):
    s = slugify(text)
    if s.startswith(prefix + "-"):
        s = s[len(prefix) + 1:]
    return s or prefix


_PT_ONLY = re.compile(r"^-?\d+(?:\.\d+)?pt$")


class _Tokens:
    def __init__(self, dual=False):
        self.by_file = {}
        self.names = set()
        self.list = []
        self.warnings = []
        self.dual = dual                  # a web target is enabled: every pt length also gets -px and -rem (AC18)

    def add(self, fname, name, value, item, category=None, _variant=False):
        base, n = name, name
        if n in self.names:
            n = "%s-%s" % (name, item["id"].lower())
        if n in self.names:
            return None
        self.names.add(n)
        rec = {"token": n, "value": value, "id": item["id"], "category": category or item.get("category"),
               "file": fname, "status": item.get("status", "observed"), "evidence": item.get("evidence", ""),
               "edited": bool(item.get("edited"))}
        self.by_file.setdefault(fname, []).append(rec)
        self.list.append(rec)
        if self.dual and not _variant and _PT_ONLY.match(str(value)):
            px, rem = px_rem(float(str(value)[:-2]))
            self.add(fname, n + "-px", px, item, category, _variant=True)
            self.add(fname, n + "-rem", rem, item, category, _variant=True)
        return rec


def _kept(approved, cat):
    return [i for i in approved.get("items", []) if i.get("keep") and i.get("category") == cat]


def build_plan(approved):
    """Pure: approved.json dict -> {files: {rel: text}, tokens: [...], provenance: {...}, warnings: [...]}"""
    media = set(approved.get("medium", []))
    targets = set(approved.get("targets") or [])
    reach = media | targets                                  # every medium this system serves: source plus enabled targets
    tk = _Tokens(dual="web-ui" in targets)
    page = {}
    imports = []
    google = {}

    for it in _kept(approved, "COL"):
        tk.add("colors", "--color-" + slugify_label(it["label"] or it["id"], "color"), str(it["value"]).strip(), it)

    fam_first = {}
    for it in _kept(approved, "TYP"):
        value = str(it["value"]).strip()
        m = _TYP.match(value)
        if m:
            fam = m.group("family").strip()
            fslug = slugify(fam)
            sub = fontmap.substitute(fam)
            fam_first.setdefault(fam, (it, sub))
            key = "--text-" + slugify_label(it["label"] or it["id"], "text")
            tk.add("typography", key + "-family", "var(--font-%s)" % fslug, it)
            tk.add("typography", key + "-size", "%spt" % fmt_num(m.group("size")), it)
            tk.add("typography", key + "-weight", m.group("weight"), it)
            if m.group("italic"):
                tk.add("typography", key + "-style", "italic", it)
            if m.group("lh"):
                tk.add("typography", key + "-line-height", "%spt" % fmt_num(m.group("lh")), it)
            if sub["google_font"]:
                google.setdefault(sub["google_font"], set()).add((int(m.group("weight")), bool(m.group("italic"))))
            continue
        r = _RATIO.search(value)
        if r:
            tk.add("typography", "--text-scale-ratio", r.group(1), it)
            if r.group(2):
                tk.add("typography", "--text-scale-base", r.group(2), it)
            continue
        tk.warnings.append("TYP %s skipped: value %r is not '<family> <size>pt <weight>[ italic][ / <lh>pt]'" % (it["id"], value))
    subs = [{"family": fam, "substitute": sub["google_font"], "google_font": sub["google_font"], "kind": sub["kind"],
             "confidence": sub["confidence"], "reason": sub["reason"], "item": it["id"]}
            for fam, (it, sub) in sorted(fam_first.items())]
    for fam, (it, sub) in fam_first.items():
        stack = ("'%s', %s" % (sub["google_font"], sub["generic"])) if sub["google_font"] else sub["generic"]
        tk.add("typography", "--font-" + slugify(fam), stack, it)

    frame_kept = False
    gap_done = lead_done = False
    for it in _kept(approved, "STR"):
        value = str(it["value"]).strip()
        typ = it.get("type") or ""
        margins = dict((k, v) for k, v in _MARGIN.findall(value))
        if (typ == "page-frame" or (not typ and len(margins) == 4)) and len(margins) == 4 and not frame_kept:
            for side in ("top", "right", "bottom", "left"):
                tk.add("spacing", "--page-margin-" + side, margins[side], it)
            page.setdefault("margin", margins)
            frame_kept = True
        elif typ == "columns" and not gap_done:
            g = re.search(r"gutter\s+(%s)" % _LEN, value)
            if g:
                tk.add("spacing", "--col-gap", g.group(1), it)
                gap_done = True
        elif typ == "rhythm" and not lead_done:
            r = re.match(r"^(\w+)\s+(%s)\s+on\s+(%s)\s+leading" % (_LEN, _LEN), value)
            if r and r.group(1) == "body":
                tk.add("spacing", "--leading-body", r.group(3), it)
                lead_done = True
    for it in _kept(approved, "SPC"):
        value, label = str(it["value"]).strip(), (it["label"] or "").lower()
        two = _SIZE2.match(value)
        margins = dict((k, v) for k, v in _MARGIN.findall(value))
        if two and ("page" in label or "slide" in label or "size" in label):
            tk.add("spacing", "--page-width", two.group(1), it)
            tk.add("spacing", "--page-height", two.group(2), it)
            page.setdefault("size", (two.group(1), two.group(2)))
        elif len(margins) == 4:
            if frame_kept:                                    # the measured page frame (STR) replaces the estimate
                continue
            for side in ("top", "right", "bottom", "left"):
                tk.add("spacing", "--page-margin-" + side, margins[side], it)
            page.setdefault("margin", margins)
        elif _LEN_ONLY.match(value):
            tk.add("spacing", "--space-" + slugify_label(it["label"] or it["id"], "space"), value, it)
        else:
            tk.warnings.append("SPC %s skipped: value %r is not a length, a page size or margins" % (it["id"], value))

    for it in _kept(approved, "RAD"):
        tk.add("radii", "--radius-" + slugify_label(it["label"] or it["id"], "radius"), str(it["value"]).strip(), it)
    for it in _kept(approved, "BRD"):
        tk.add("borders", "--border-" + slugify_label(it["label"] or it["id"], "border"), str(it["value"]).strip(), it)
    for it in _kept(approved, "SHD"):
        lab = it["label"] or it["id"]
        if lab.lower().startswith("opacity"):
            tk.add("elevation", "--opacity-" + slugify_label(lab, "opacity"), str(it["value"]).strip(), it)
        else:
            tk.add("elevation", "--shadow-" + slugify_label(lab, "shadow"), str(it["value"]).strip(), it)
    if reach & WEB_MEDIA:
        for it in _kept(approved, "MOT"):
            tk.add("motion", "--motion-" + slugify_label(it["label"] or it["id"], "motion"), str(it["value"]).strip(), it)
    # user additions without a category the build understands
    for it in approved.get("items", []):
        if it.get("keep") and it.get("category") is None:
            tk.warnings.append("%s skipped: cannot tell what kind of token %r is (use a hex colour or a length)" % (it["id"], it.get("value")))

    files = {}
    for fname, recs in tk.by_file.items():
        lines = [GENERATED, ":root {"]
        for r in recs:
            lines.append("  %s: %s;" % (r["token"], r["value"]))
        lines.append("}")
        files["tokens/%s.css" % fname] = "\n".join(lines) + "\n"
    if google:
        lines = [GENERATED, "/* Google Fonts substitutes; the PDF's own fonts are never shipped (see readme: Substitutions & gaps) */"]
        for name in sorted(google):
            lines.append(fontmap.google_import(name, sorted(google[name])))
        files["tokens/fonts.css"] = "\n".join(lines) + "\n"
    if (reach & PRINT_LIKE) and page.get("size"):
        w, h = page["size"]
        mg = page.get("margin")
        css = ["@page {", "  size: %s %s;" % (w, h)]
        if mg:
            css.append("  margin: %s %s %s %s;" % (mg["top"], mg["right"], mg["bottom"], mg["left"]))
        css.append("}")
        files["tokens/page.css"] = GENERATED + "\n" + "\n".join(css) + "\n"
    for name in ORDER:
        if "tokens/%s.css" % name in files:
            imports.append('@import url("tokens/%s.css");' % name)
    files["styles.css"] = "\n".join(imports) + "\n"

    prov = {}
    for r in tk.list:
        e = {"id": r["id"], "status": r["status"], "evidence": r["evidence"], "source": "pdf"}
        if r["edited"]:
            e["edited"] = True
        prov[r["token"]] = e
    return {"files": files, "tokens": tk.list, "provenance": prov, "warnings": tk.warnings, "substitutions": subs}


def _preview_source(env):
    explicit = (env.get("DFP_PREVIEW_JS") or "").strip()
    if explicit:
        p = Path(explicit)
        if not p.is_file():
            raise Blocked("blocked: DFP_PREVIEW_JS points to a missing ds-preview runtime: %s" % explicit)
        return p
    here = Path(__file__).resolve().parent.parent
    bundled = here / "assets" / "ds-preview.js"
    if bundled.is_file():
        return bundled
    sibling = here.parent / "design-generating" / "ds-preview.js"
    if sibling.is_file():
        return sibling
    raise Blocked("blocked: no ds-preview.js found (bundled assets/ds-preview.js is missing from this skill)")


def ensure_analysis_gitignore(ds):
    gi = Path(ds) / "_analysis" / ".gitignore"
    have = gi.read_text(encoding="utf-8").splitlines() if gi.is_file() else []
    want = [x for x in ("renders/", "verify/") if x not in have]
    if want or not gi.is_file():
        gi.parent.mkdir(parents=True, exist_ok=True)
        with open(str(gi), "w", encoding="utf-8", newline="\n") as fh:
            fh.write("\n".join(have + want) + "\n")


def _write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(str(path), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def scaffold(ds_dir, preview_js=None, env=None):
    env = os.environ if env is None else env
    ds = Path(ds_dir)
    ap = ds / "_analysis" / "approved.json"
    if not ap.is_file():
        raise FileNotFoundError("no _analysis/approved.json: the gate has not passed")
    src = Path(preview_js) if preview_js else _preview_source(env)
    if not src.is_file():
        raise Blocked("blocked: ds-preview runtime not found: %s" % src)
    approved = json.loads(ap.read_text(encoding="utf-8"))
    plan = build_plan(approved)

    tokens_dir = ds / "tokens"
    if tokens_dir.is_dir():                                    # drop generated files this run no longer produces
        for f in tokens_dir.glob("*.css"):
            rel = "tokens/%s" % f.name
            if rel not in plan["files"] and f.read_text(encoding="utf-8").startswith(GENERATED):
                f.unlink()
    for rel, text in plan["files"].items():
        _write(ds / rel, text)
    _write(ds / "provenance.json", json.dumps(plan["provenance"], indent=2, ensure_ascii=False) + "\n")
    _write(ds / "_analysis" / "substitutions.json", json.dumps(plan["substitutions"], indent=2, ensure_ascii=False) + "\n")

    man_path = ds / "_ds_manifest.json"
    manifest = {"namespace": "DS_" + (slugify(ds.resolve().name).replace("-", "_") or "design_system"), "components": []}
    if man_path.is_file():                                     # never clobber components built after a first scaffold
        try:
            old = json.loads(man_path.read_text(encoding="utf-8"))
            manifest["namespace"] = old.get("namespace", manifest["namespace"])
            manifest["components"] = old.get("components", [])
        except ValueError:
            pass
    _write(man_path, json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
    shutil.copyfile(str(src), str(ds / "_ds_preview.js"))
    ensure_analysis_gitignore(ds)
    return {"ok": True, "files": sorted(plan["files"]) + ["provenance.json", "_ds_manifest.json", "_ds_preview.js"],
            "tokens": len(plan["tokens"]), "warnings": plan["warnings"]}
